  function detect() {
    try {
      var q = new URLSearchParams(location.search).get('lang');
      if (q === 'en' || q === 'de' || q === 'ru') return q;
    } catch (e) {}
    try {
      var stored = localStorage.getItem(STORAGE);
      if (stored === 'en' || stored === 'de' || stored === 'ru') return stored;
    } catch (e) {}
    var nav = (navigator.language || 'en').toLowerCase();
    if (nav.indexOf('ru') === 0) return 'ru';
    if (nav.indexOf('de') === 0) return 'de';
    return 'en';
  }

  function apply(lang) {
    var table = STRINGS[lang] || STRINGS.en;
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (!table[key]) return;
      if (el.hasAttribute('data-i18n-html')) el.innerHTML = table[key];
      else el.textContent = table[key];
    });
    document.querySelectorAll('[data-i18n-attr]').forEach(function (el) {
      el.getAttribute('data-i18n-attr').split(',').forEach(function (pair) {
        var parts = pair.split(':');
        if (parts.length !== 2) return;
        if (table[parts[1]]) el.setAttribute(parts[0], table[parts[1]]);
      });
    });
    var titleKey = document.body.getAttribute('data-title-key');
    if (titleKey && table[titleKey]) document.title = table[titleKey];
    var desc = document.querySelector('meta[name="description"]');
    var descKey = document.body.getAttribute('data-desc-key');
    if (desc && descKey && table[descKey]) desc.setAttribute('content', table[descKey]);
    document.querySelectorAll('[data-set-lang]').forEach(function (btn) {
      btn.classList.toggle('active', btn.getAttribute('data-set-lang') === lang);
    });
    var locale = lang === 'de' ? 'de_DE' : lang === 'ru' ? 'ru_RU' : 'en_US';
    var og = document.querySelector('meta[property="og:locale"]');
    if (og) og.setAttribute('content', locale);
    try { localStorage.setItem(STORAGE, lang); } catch (e) {}
  }

  document.addEventListener('click', function (event) {
    var btn = event.target.closest('[data-set-lang]');
    if (!btn) return;
    apply(btn.getAttribute('data-set-lang'));
  });

  apply(detect());
