export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

export function detectLang(): Lang {
  if (typeof window === 'undefined') {
    return 'en';
  }
  try {
    const query = new URLSearchParams(window.location.search).get('lang');
    if (query === 'en' || query === 'de' || query === 'ru') {
      return query;
    }
  } catch {
    // ignore
  }
  try {
    const stored = window.localStorage.getItem('spectralizer-lang');
    if (stored === 'en' || stored === 'de' || stored === 'ru') {
      return stored;
    }
  } catch {
    // ignore
  }
  const nav = (window.navigator.language || 'en').toLowerCase();
  if (nav.startsWith('ru')) {
    return 'ru';
  }
  if (nav.startsWith('de')) {
    return 'de';
  }
  return 'en';
}

export function hopKey(value: number): string {
  if (value === 0.25) {
    return 'hop75';
  }
  if (value === 0.5) {
    return 'hop50';
  }
  return 'hopNone';
}
